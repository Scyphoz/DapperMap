package dev.scyphoz.dappermap.dynamic;

import com.hypixel.hytale.protocol.packets.setup.AssetFinalize;
import com.hypixel.hytale.protocol.packets.setup.AssetInitialize;
import com.hypixel.hytale.protocol.packets.setup.AssetPart;
import com.hypixel.hytale.protocol.packets.setup.RequestCommonAssetsRebuild;
import com.hypixel.hytale.server.core.asset.common.CommonAsset;
import com.hypixel.hytale.server.core.io.PacketHandler;
import com.hypixel.hytale.server.core.universe.PlayerRef;
import dev.scyphoz.dappermap.service.DapperMapServerLoad;
import dev.scyphoz.dappermap.util.DapperMapUtil;
import java.util.Map;
import java.util.LinkedHashMap;
import java.util.UUID;
import java.util.concurrent.CompletableFuture;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.ConcurrentMap;

/** Sends generated PNG assets to a player's client and avoids retransmitting identical bytes. */
public final class DynamicAssetPublisher {
    /**
     * Per-player marker images (by path) for the settings preview. Access-ordered and bounded:
     * the least recently delivered image is dropped, so icons seen late in a session still
     * reach the preview. Guarded by the map's own monitor.
     */
    private static final ConcurrentMap<UUID, Map<String, byte[]>> MARKER_BYTES = new ConcurrentHashMap<>();
    /**
     * Remembered SHA-256 of shared, never-modified PNG arrays (renderer caches, tinted icons).
     * byte[] keys use identity equals/hashCode, so this is an identity map; entries vanish when
     * the cache that owns the array drops it.
     */
    private static final Map<byte[], String> SHARED_HASHES =
            java.util.Collections.synchronizedMap(new java.util.WeakHashMap<>());
    private static final int PART_SIZE = 2621440;
    /**
     * Paths (and content hashes) already sent, per player and tied to the connection they were
     * sent on: a reconnect has a new PacketHandler, so records from the old connection (which a
     * late delivery on another thread could re-insert after a disconnect clear) are never trusted.
     */
    private record Delivered(PacketHandler owner, Map<String, String> paths) { }
    /** Delivered records kept per connection; the least recently used are forgotten (and re-sent if needed). */
    private static final int DELIVERED_LIMIT = 2048;
    private static final ConcurrentMap<UUID, Delivered> DELIVERED = new ConcurrentHashMap<>();

    /** This connection's delivered paths, or null (records from another connection don't count). */
    private static Map<String, String> deliveredFor(UUID uuid, PacketHandler owner) {
        Delivered delivered = uuid == null ? null : DELIVERED.get(uuid);
        return delivered != null && delivered.owner() == owner ? delivered.paths() : null;
    }

    /**
     * In-memory CommonAsset wrapper that publishes a generated image through Hytale's asset
     * protocol (previously its own file, DynamicMinimapAsset.java).
     */
    private static final class DynamicMinimapAsset extends CommonAsset {
        private final byte[] data;

        DynamicMinimapAsset(String path, String hash, byte[] data) {
            super(path, hash, data);
            this.data = data;
        }

        @Override
        protected CompletableFuture<byte[]> getBlob0() {
            return CompletableFuture.completedFuture(this.data);
        }
    }

    /** Generated bytes and their content hash prepared away from the world thread. */
    public static final class PreparedAsset {
        private final String path;
        private final byte[] data;
        private final DynamicMinimapAsset asset;
        private PreparedAsset(String path, byte[] data) {
            this(path, data, CommonAsset.hash(data));
        }
        private PreparedAsset(String path, byte[] data, String hash) {
            this.path = path;
            this.data = data;
            this.asset = new DynamicMinimapAsset(path, hash, data);
        }
        public PreparedAsset withPath(String path) {
            return this.path.equals(path) ? this : new PreparedAsset(path, this.data, this.hash());
        }
        public String path() { return this.path; }
        public String hash() { return this.asset.getHash(); }
        /** Encoded PNG bytes; shared and never modified. */
        byte[] data() { return this.data; }
    }

    public static PreparedAsset prepare(String path, byte[] data) {
        return path == null || data == null || data.length == 0 ? null : new PreparedAsset(path, data);
    }

    /**
     * Content hash of a shared PNG array that is reused unchanged (renderer caches, tinted
     * icons), computed once per array. Use only for arrays that are never modified; freshly
     * encoded images (terrain frames) should use {@link #prepare} directly.
     */
    public static String rememberedHash(byte[] data) {
        String hash = SHARED_HASHES.get(data);
        if (hash == null) {
            // Hash outside the lock; a concurrent duplicate computes the same value.
            hash = CommonAsset.hash(data); // Already lower-case hex (HashUtil.sha256).
            SHARED_HASHES.put(data, hash);
        }
        return hash;
    }

    /** {@link #prepare} for a shared, never-modified array: its hash is remembered across calls. */
    public static PreparedAsset prepareShared(String path, byte[] data) {
        return path == null || data == null || data.length == 0 ? null
                : new PreparedAsset(path, data, rememberedHash(data));
    }

    /** {@link #deliver(PlayerRef, String, byte[])} for a shared, never-modified array (remembered hash). */
    public static boolean deliverShared(PlayerRef playerRef, String path, byte[] data) {
        return deliverPrepared(playerRef, prepareShared(path, data), false);
    }

    /**
     * {@link #deliverShared}, then asks the client to rebuild its common assets (needed once for
     * the clip masks, which are resolved from the common UI asset set).
     */
    public static boolean deliverSharedWithRebuild(PlayerRef playerRef, String path, byte[] data) {
        return deliverPrepared(playerRef, prepareShared(path, data), true);
    }

    /** True when this player's current connection was already sent exactly this content at this path. */
    public static boolean isDelivered(PlayerRef playerRef, String path, String hash) {
        if (playerRef == null || path == null || hash == null) return false;
        Map<String, String> delivered = deliveredFor(playerRef.getUuid(), playerRef.getPacketHandler());
        return delivered != null && hash.equals(delivered.get(path));
    }

    public static boolean deliver(PlayerRef playerRef, PreparedAsset prepared) {
        return deliverPrepared(playerRef, prepared, false);
    }

    private DynamicAssetPublisher() {
    }

    /**
     * Forgets everything recorded for a player (delivered paths and preview marker images).
     * Call on disconnect and whenever the client may have dropped its dynamic assets.
     */
    public static void clear(UUID uuid) {
        if (uuid != null) {
            DELIVERED.remove(uuid);
            MARKER_BYTES.remove(uuid);
        }

    }

    /** Total delivered-image records across online players (for /dappermap admin stats). */
    public static int deliveredEntries() {
        int total = 0;
        for (Delivered delivered : DELIVERED.values()) total += delivered.paths().size();
        return total;
    }

    public static byte[] markerBytes(UUID uuid, String path) {
        Map<String, byte[]> assets = uuid == null ? null : MARKER_BYTES.get(uuid);
        if (assets == null) return null;
        synchronized (assets) {
            return assets.get(path); // Shared, never modified: encoded PNGs are immutable once prepared.
        }
    }

    private static boolean deliverPrepared(PlayerRef playerRef, PreparedAsset prepared, boolean rebuildCommonAssets) {
        if (playerRef == null || prepared == null) return false;
        PacketHandler packetHandler = playerRef.getPacketHandler();
        if (packetHandler == null) return false;
        UUID uuid = playerRef.getUuid();
        String path = prepared.path;
        byte[] data = prepared.data;
        String hash = prepared.asset.getHash();
        // Already on this connection's client with the same content: nothing to send.
        if (uuid != null) {
            Map<String, String> delivered = deliveredFor(uuid, packetHandler);
            if (delivered != null && hash.equals(delivered.get(path))) {
                rememberMarker(uuid, path, data); // Keep it in the preview store (refreshes its LRU position).
                return true;
            }
        }
        try {
            // Hytale's asset protocol: initialise, the bytes in parts, finalise.
            AssetInitialize initialise = new AssetInitialize(prepared.asset.toPacket(), data.length);
            packetHandler.writeNoCache(initialise);
            for (byte[] part : splitBytes(data, PART_SIZE)) packetHandler.writeNoCache(new AssetPart(part));
            packetHandler.writeNoCache(new AssetFinalize());
            DapperMapServerLoad.recordAsset(data.length); // Counter only (admin stats).
            rememberMarker(uuid, path, data);
            if (rebuildCommonAssets) packetHandler.writeNoCache(new RequestCommonAssetsRebuild());
            if (uuid != null) {
                // A record set from an older connection is replaced, never added to.
                Map<String, String> delivered = DELIVERED.compute(uuid, (ignored, old) ->
                        old != null && old.owner() == packetHandler ? old
                                : new Delivered(packetHandler, DapperMapUtil.lruMap(DELIVERED_LIMIT, true))).paths();
                delivered.put(path, hash); // LRU: the oldest record drops out, not all of them.
            }
            return true;
        } catch (Exception sendFailed) {
            return false; // Not recorded as delivered, so it is sent again next time.
        }
    }

    /** Marker images (including creature icons) are kept, by reference, for the settings preview. */
    private static void rememberMarker(UUID uuid, String path, byte[] data) {
        if (uuid == null || !path.startsWith("UI/DapperMap/")
                || !(path.contains("/mk-") || path.contains("/bettermap-")
                || path.contains("/worldmap-") || path.contains("/creature-")
                || path.contains("/player-"))) return; // Player head icons show in the settings preview too.
        // Least recently delivered image dropped beyond the HUD's slot count; guarded by its own monitor.
        Map<String, byte[]> markers = MARKER_BYTES.computeIfAbsent(uuid,
                ignored -> DapperMapUtil.lruMap(DynamicMinimapHud.MARKER_SLOTS, false));
        synchronized (markers) {
            markers.put(path, data); // Reference, not a copy: the bytes are immutable.
        }
    }

    private static byte[][] splitBytes(byte[] data, int partSize) {
        if (data.length <= partSize) return new byte[][]{data};
        int count = (data.length + partSize - 1) / partSize; // At least 2 here.
        byte[][] parts = new byte[count][];
        for (int i = 0; i < count; ++i) {
            int start = i * partSize;
            parts[i] = java.util.Arrays.copyOfRange(data, start, Math.min(start + partSize, data.length));
        }
        return parts;
    }

    /** World-thread bookkeeping for the bounded image paths already sent to this client. */
    static final class ImagePublicationCache {
        private String activePath;
        /** False for caches whose paths end in a meaning-bearing number (compass heading buckets). */
        private final boolean slotted;
        ImagePublicationCache() { this(true); }
        ImagePublicationCache(boolean slotted) { this.slotted = slotted; }
        private static final java.util.regex.Pattern SLOT = java.util.regex.Pattern.compile("(.*?)([0-9]+)(\\.png)$");
        private final Map<String, String> hashesByPath = new LinkedHashMap<>();

        /**
         * Sends {@code prepared} under a slot the client is not showing, unless the client already
         * holds the same image in this cache (matched by hash; nothing is sent then). Returns the
         * path to show, or null when the delivery failed. The caller marks it {@link #shown} once
         * its AssetPath is set. World thread only.
         */
        String publish(PlayerRef ref, PreparedAsset prepared) {
            String existing = pathFor(prepared.hash());
            if (existing != null) return existing;
            PreparedAsset publication = prepared.withPath(nonActivePath(prepared.path()));
            if (!deliver(ref, publication)) return null;
            remember(publication.path(), publication.hash());
            return publication.path();
        }

        private String pathFor(String hash) {
            for (var entry : hashesByPath.entrySet())
                if (entry.getValue().equals(hash)) return entry.getKey();
            return null;
        }

        /**
         * Marks the path the client now displays; nonActivePath never reuses it. Called after the
         * AssetPath Set, so a delivery that aborts before it can't unprotect the shown image.
         */
        void shown(String path) { activePath = path; }

        private void remember(String path, String hash) {
            hashesByPath.remove(path); // Replacing a slot invalidates its previous content.
            hashesByPath.put(path, hash);
            if (hashesByPath.size() > 16) hashesByPath.remove(hashesByPath.keySet().iterator().next());
        }

        private String nonActivePath(String candidate) {
            if (!candidate.equals(activePath)) return candidate;
            // Unslotted names alternate with a "-b" twin, so renumbering never lands on another heading.
            if (!this.slotted) return candidate.endsWith("-b.png")
                    ? candidate.substring(0, candidate.length() - 6) + ".png"
                    : candidate.substring(0, candidate.length() - 4) + "-b.png";
            var match = SLOT.matcher(candidate);
            // Defensive: never throw on the world thread; give an unslotted path a slot suffix.
            if (!match.matches()) return candidate.substring(0, candidate.length() - 4) + "-1.png";
            return match.group(1) + ((Integer.parseInt(match.group(2)) + 1) & 15) + match.group(3);
        }

        void clear() { hashesByPath.clear(); activePath = null; }
    }
}
